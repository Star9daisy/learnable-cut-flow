import shutil
from argparse import ArgumentParser
from pathlib import Path

parser = ArgumentParser()
_ = parser.add_argument("folder")
args = parser.parse_args()
folder_path = Path(args.folder).absolute()

print(f"Cleaning folder {folder_path.relative_to(Path.cwd())}...")

removed_folders = ["bin", "Cards", "HTML", "lib", "Source", "SubProcesses"]
removed_files = [
    "myprocid",
    "README",
    "madevent.tar.gz",
    "index.html",
    "README.systematics",
    "MGMEVersion.txt",
    "TemplateVersion.txt",
]
allowed_file_suffixes = [".gz", ".root", ".txt"]

if Path("py.py").exists():
    Path("py.py").unlink()

for path in folder_path.glob("*"):
    # General files and folders
    if path.is_dir() and path.name in removed_folders:
        print(f"Removed {path.relative_to(Path.cwd())}")
        shutil.rmtree(path, ignore_errors=True)
    elif path.is_file() and path.name in removed_files:
        print(f"Removed {path.relative_to(Path.cwd())}")
        path.unlink(missing_ok=True)
    else:
        print(f"Keep {path.relative_to(Path.cwd())}")

    # Events
    for path in (folder_path / "Events").glob("*"):
        # Ignore banner files generated by multi_run
        if not path.is_dir():
            continue

        for file in path.glob("*"):
            if file.suffix not in allowed_file_suffixes:
                print(f"Removed {file.relative_to(Path.cwd())}")
                file.unlink(missing_ok=True)
